import { layoutFormation, GK_COORD } from './formationLayout';

/**
 * 전술 옵션 호버 프리뷰용 데이터.
 *
 * 좌표계: x, y 모두 0~100(%). x는 왼쪽(0)→오른쪽(100), y는 우리 진영 골라인(0)→상대 진영 골라인(100).
 * 우리 팀 11명 + 상대 팀 11명을 한 미니 피치에 같이 띄우기 때문에, layoutFormation()이 원래
 * 만들어주는 "자기 진영 절반 안"의 배치를 그대로 쓴다(예전처럼 피치 전체로 늘려 펴지 않는다) —
 * 그래야 두 팀이 하프라인을 기준으로 자연스럽게 마주보고 겹치지 않는다.
 *
 * 슬롯은 고정된 이름(cb1/lb 등)이 아니라 실제 선택된 포메이션의 role(GK/CB/FB/WB/DM/CM/AM/WG/ST)과
 * 좌표를 그대로 쓴다 — 포메이션이 바뀌면 프리뷰의 기본 배치도 그 포메이션 모양으로 함께 바뀐다.
 * 전술 옵션 오버라이드도 "왼쪽 풀백" 같은 고정 슬롯이 아니라 role/좌우 위치로 대상을 찾기 때문에
 * 어떤 포메이션(백3/4/5, 윙어 유무 등)이 선택돼 있어도 동작한다(단, transform/ballPath는 항상
 * 우리 팀 11명 슬롯만 대상으로 한다 - 상대 팀은 별도로 다룬다).
 */

function clamp(v, lo, hi) {
  return Math.max(lo, Math.min(hi, v));
}

/** 우리 팀 슬롯 - layoutFormation의 "자기 진영 절반" 배치를 그대로 쓰되, y만 이 파일의 좌표계(0=우리 골문, 100=상대 골문)로 뒤집는다. */
export function buildOwnHalfSlots(formation) {
  const coords = layoutFormation(formation);
  const slots = formation.positions.map((role, i) => ({ role, x: coords[i].x, y: 100 - coords[i].y }));
  slots.unshift({ role: 'GK', x: GK_COORD.x, y: 100 - GK_COORD.y });
  return slots;
}

/** ownHalfSlots를 반대쪽 절반으로(좌우+상하 모두) 뒤집어 마주보는 상대 팀 배치를 만든다. */
function mirrorToOppHalf(ownHalfSlots) {
  return ownHalfSlots.map(s => ({ ...s, x: 100 - s.x, y: 100 - s.y }));
}

/** 상대 팀 슬롯 - 상대 팀의 실제 포메이션을 우리 팀과 마주보도록 뒤집는다. */
export function buildOppHalfSlots(formation) {
  return mirrorToOppHalf(buildOwnHalfSlots(formation));
}

