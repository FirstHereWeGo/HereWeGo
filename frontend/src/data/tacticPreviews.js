const CLUSTER_K_START = 1; // 첫 경유지에서는 원래 대형(자기 offset 100%) 그대로
const CLUSTER_K_END = 0.35; // 마지막 경유지에서는 offset을 35%로 줄여 볼 주변으로 바짝 모인다

/**
 * 22명(우리+상대, GK 제외) 각각의 "전체 22명 중심점 대비 자기 offset"은 유지한 채, 그 중심을
 * ballPoint로 옮기고 stepRatio(0~1, 현재 경유지/전체 경유지)가 커질수록 offset을 줄여서
 * 두 팀이 볼 주변으로 점점 뒤섞여 몰리게 만든다. 선수마다 원래 offset(방향·거리)이 달라서
 * 같은 스텝이라도 각자 다른 방향/거리로 움직인다 — 획일적으로 다 같이 한 방향으로 밀리지 않는다.
 * ballPoint가 없는(= ballPath가 없는) 옵션에서는 그냥 원래 대형 그대로 반환한다.
 */
export function clusterAroundBall(mineBase, oppBase, ballPoint, stepRatio) {
  if (!ballPoint) return { mine: mineBase, opp: oppBase };
  const outfield = [...mineBase, ...oppBase].filter(s => s.role !== 'GK');
  const cx = outfield.reduce((sum, s) => sum + s.x, 0) / outfield.length;
  const cy = outfield.reduce((sum, s) => sum + s.y, 0) / outfield.length;
  const k = CLUSTER_K_START + (CLUSTER_K_END - CLUSTER_K_START) * stepRatio;
  const move = (s) => (s.role === 'GK' ? s : {
    ...s,
    x: clamp(ballPoint.x + (s.x - cx) * k, 2, 98),
    y: clamp(ballPoint.y + (s.y - cy) * k, 2, 98),
  });
  return { mine: mineBase.map(move), opp: oppBase.map(move) };
}

/** slots 중 target과 같은 객체(참조)만 patch를 덮어써서 교체한 새 배열을 반환한다. */
function mapSlot(slots, target, patch) {
  if (!target) return slots;
  return slots.map(s => (s === target ? { ...s, ...patch(s) } : s));
}

const WIDE_DEFENDER = new Set(['FB', 'WB']);
const CENTRAL_MID = new Set(['DM', 'CM', 'AM']);

function widePlayer(slots, side, roles) {
  const pool = slots.filter(s => roles.has(s.role) && (side === 'L' ? s.x < 50 : s.x > 50));
  if (!pool.length) return null;
  return side === 'L' ? pool.reduce((a, b) => (a.x < b.x ? a : b)) : pool.reduce((a, b) => (a.x > b.x ? a : b));
}

function deepestCentralMid(slots) {
  const pool = slots.filter(s => CENTRAL_MID.has(s.role));
  if (!pool.length) return null;
  return pool.reduce((a, b) => (a.y < b.y ? a : b));
}

/** 중앙 미드필더 중 가장 전방(공격 지향)에 있는 선수 - deepestCentralMid의 반대. */
function mostAdvancedCentralMid(slots) {
  const pool = slots.filter(s => CENTRAL_MID.has(s.role));
  if (!pool.length) return null;
  return pool.reduce((a, b) => (a.y > b.y ? a : b));
}

function applyOverlap(slots, side) {
  const fb = widePlayer(slots, side, WIDE_DEFENDER);
  if (!fb) return slots;
  const dirWide = side === 'L' ? -1 : 1;
  let s = mapSlot(slots, fb, m => ({ x: clamp(m.x + dirWide * 3, 2, 98), y: clamp(m.y + 26, 2, 98) }));
  const wg = widePlayer(slots, side, new Set(['WG']));
  if (wg) {
    const dirIn = side === 'L' ? 1 : -1;
    s = mapSlot(s, wg, m => ({ x: clamp(m.x + dirIn * 8, 2, 98) }));
  }
  return s;
}

