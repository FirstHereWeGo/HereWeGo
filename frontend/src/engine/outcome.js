/**
 * 시뮬레이션 재생 1회의 결과를 xG 확률로 굴린다.
 * - 'conceded' 장면: true = 남아공이 득점(실점당함)
 * - 'chance'   장면: true = 대한민국이 득점
 *
 * 주의: 이건 "그 순간의 진짜 미래"가 아니라 계산된 xG를 확률로 쓴 한 번의 시행이다.
 * 재생할 때마다 다른 결과가 나올 수 있으며, 이는 xG 개념 자체가 원래 그렇다는 걸
 * 보여주는 의도된 설계다 (결과 화면의 승/무/패는 이 단발 시행이 아니라 포아송
 * 기대값 기반이므로 재생 결과와 무관하게 항상 일관된 수치를 유지한다).
 */
export function rollOutcome(xg) {
  return Math.random() < xg;
}
